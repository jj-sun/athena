export const OTHER_CATEGORY = 'other';

export const ICON_CATEGORY_OPTIONS = [
  { label: '全部类别', value: 'all' },
  ...ICON_CATEGORIES.map((item) => ({ label: item.label, value: item.key })),
  { label: '其他', value: OTHER_CATEGORY },
];

const TOKEN_CATEGORY = new Map<string, string>();
for (const category of ICON_CATEGORIES) {
  for (const token of category.tokens) {
    if (!TOKEN_CATEGORY.has(token)) {
      TOKEN_CATEGORY.set(token, category.key);
    }
  }
}

/** 填充图标统一以 `-filled` 结尾（如 `user-filled`） */
export function isFilledIcon(stem: string): boolean {
  return stem.endsWith('-filled');
}

/** 根据图标名中的关键词归类，未命中返回 other */
export function getIconCategory(stem: string): string {
  const base = stem.replace(/-filled$/, '');
  for (const token of base.split('-')) {
    const category = TOKEN_CATEGORY.get(token);
    if (category) {
      return category;
    }
  }
  return OTHER_CATEGORY;
}
